import Link from "next/link";
import Image from "next/image";
import { notFound } from "next/navigation";
import type { Metadata } from "next";
import styles from "../Services.module.css";
import initTranslations from "@/app/i18n";
import TranslationsProvider from "@/components/TranslationsProvider";
import Header from "@/components/Header/Header";
import Footer from "@/components/Footer/Footer";
import CTAActions from "@/components/CTASection/CTAActions";
import { ProductSite } from "@/const/product-site";
import { servicesList, getServiceBySlug, getServiceContent, servicesUi, ServiceLang } from "@/const/services-data";
import { i18nConfig } from "../../../../../i18nConfig";
import {
  ORGANIZATION_ID,
  absoluteUrl,
  breadcrumbJsonLd,
  buildPageMetadata,
  homeCrumb,
  jsonLdString,
  localePath,
  localeUrl,
} from "@/utils/seo";

const i18nNamespaces = ["common"];

// Generated by scripts/generate-og.mjs
const serviceOgImage = (slug: string, lang: string) =>
  `/og/services/${slug}-${["ru", "en", "tj"].includes(lang) ? lang : "ru"}.jpg`;

type PageProps = { params: Promise<{ lang: string; slug: string }> };

export const dynamicParams = false;

export function generateStaticParams() {
  return i18nConfig.locales.flatMap((lang) => servicesList.map((service) => ({ lang, slug: service.slug })));
}

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { lang, slug } = await params;
  const service = getServiceBySlug(slug);
  if (!service) return {};
  const content = getServiceContent(service, lang);

  return buildPageMetadata({
    lang,
    path: `services/${slug}`,
    title: content.metaTitle,
    description: content.metaDescription,
    image: { url: serviceOgImage(slug, lang), width: 1200, height: 630, alt: content.title },
  });
}

export default async function ServicePage({ params }: PageProps) {
  const { lang, slug } = await params;
  const service = getServiceBySlug(slug);
  if (!service) notFound();

  const { t, resources } = await initTranslations(lang, i18nNamespaces);
  const ui = servicesUi[lang as ServiceLang] ?? servicesUi.ru;
  const content = getServiceContent(service, lang);
  const url = localeUrl(lang, `services/${slug}`);
  const cases = service.relatedCases
    .map((caseSlug) => ProductSite.find((p) => p.slug === caseSlug))
    .filter((p): p is NonNullable<typeof p> => Boolean(p));
  const otherServices = servicesList.filter((s) => s.slug !== slug);

  const jsonLd = [
    breadcrumbJsonLd([
      homeCrumb(lang),
      { name: ui.breadcrumb, url: localeUrl(lang, "services") },
      { name: content.name, url },
    ]),
    {
      "@context": "https://schema.org",
      "@type": "Service",
      "@id": `${url}#service`,
      name: content.title,
      serviceType: content.name,
      description: content.metaDescription,
      url,
      image: absoluteUrl(serviceOgImage(slug, lang)),
      provider: { "@id": ORGANIZATION_ID },
      areaServed: { "@type": "Country", name: "Tajikistan" },
      availableLanguage: ["ru", "tg", "en"],
    },
    {
      "@context": "https://schema.org",
      "@type": "FAQPage",
      mainEntity: content.faq.map((item) => ({
        "@type": "Question",
        name: item.q,
        acceptedAnswer: { "@type": "Answer", text: item.a },
      })),
    },
  ];

  return (
    <TranslationsProvider namespaces={i18nNamespaces} locale={lang} resources={resources}>
      <main className={styles.main}>
        <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: jsonLdString(jsonLd) }} />
        <div className="header-global">
          <Header />
        </div>

        <div className={styles.container}>
          <nav className={styles.breadcrumbs} aria-label="Breadcrumb">
            <Link href={localePath(lang)} className={styles.breadcrumbLink}>
              {homeCrumb(lang).name}
            </Link>
            <span className={styles.breadcrumbSeparator}>/</span>
            <Link href={localePath(lang, "services")} className={styles.breadcrumbLink}>
              {ui.breadcrumb}
            </Link>
            <span className={styles.breadcrumbSeparator}>/</span>
            <span className={styles.breadcrumbCurrent}>{content.name}</span>
          </nav>

          <header className={styles.hero}>
            <span className={styles.badge}>
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={service.icon} alt="" className={styles.badgeIcon} width={20} height={20} />
              Dushanbe Soft
            </span>
            <h1 className={styles.title}>{content.title}</h1>
            <p className={styles.lead}>{content.lead}</p>
          </header>

          <div className={styles.layout}>
            <article className={styles.content}>
              {content.sections.map((section) => (
                <section key={section.heading} className={styles.section}>
                  <h2 className={styles.sectionHeading}>{section.heading}</h2>
                  <p className={styles.sectionText}>{section.text}</p>
                  {section.bullets && (
                    <ul className={styles.bulletList}>
                      {section.bullets.map((bullet) => (
                        <li key={bullet} className={styles.bulletItem}>
                          {bullet}
                        </li>
                      ))}
                    </ul>
                  )}
                </section>
              ))}

              {cases.length > 0 && (
                <section className={styles.section}>
                  <h2 className={styles.sectionHeading}>{ui.casesTitle}</h2>
                  <div className={styles.casesGrid}>
                    {cases.map((project) => {
                      const caseTitle = t(`projects.${project.slug}.title`, { defaultValue: project.slug });
                      return (
                        <Link
                          key={project.slug}
                          href={localePath(lang, `cases/${project.slug}`)}
                          className={styles.caseCard}
                        >
                          <div className={styles.caseImage}>
                            <Image
                              src={project.imageSrc}
                              alt={caseTitle}
                              fill
                              sizes="(max-width: 640px) 100vw, 280px"
                            />
                          </div>
                          <span className={styles.caseTitle}>{caseTitle}</span>
                        </Link>
                      );
                    })}
                  </div>
                </section>
              )}

              <section className={styles.section}>
                <h2 className={styles.sectionHeading}>{ui.faqTitle}</h2>
                <div className={styles.faqList}>
                  {content.faq.map((item) => (
                    <details key={item.q} className={styles.faqItem}>
                      <summary className={styles.faqQuestion}>{item.q}</summary>
                      <p className={styles.faqAnswer}>{item.a}</p>
                    </details>
                  ))}
                </div>
              </section>

              <section className={styles.cta}>
                <h2 className={styles.ctaTitle}>{ui.ctaTitle}</h2>
                <p className={styles.ctaText}>{ui.ctaText}</p>
                <CTAActions primaryBtnText={t("cta.primaryBtn", ui.ctaButton)} />
              </section>
            </article>

            <aside className={styles.sidebar}>
              <div className={styles.sideCard}>
                <h2 className={styles.sideTitle}>{ui.otherServices}</h2>
                <ul className={styles.sideLinks}>
                  {otherServices.map((other) => (
                    <li key={other.slug}>
                      <Link href={localePath(lang, `services/${other.slug}`)} className={styles.sideLink}>
                        {getServiceContent(other, lang).name}
                      </Link>
                    </li>
                  ))}
                </ul>
              </div>
            </aside>
          </div>
        </div>

        <Footer lang={lang} />
      </main>
    </TranslationsProvider>
  );
}
